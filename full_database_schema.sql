-- Gerenciar Membro da Equipe
CREATE OR REPLACE FUNCTION public.manage_team_member(p_access_key text, p_member_data jsonb, p_action text)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_portal_id bigint;
BEGIN
    SELECT id INTO v_portal_id FROM public.ict_portals WHERE access_key = p_access_key;
    IF v_portal_id IS NULL THEN
        RAISE EXCEPTION 'Chave de acesso inválida.';
    END IF;

    IF p_action = 'create' THEN
        INSERT INTO public.team_members (portal_id, name, role, email, phone)
        VALUES (v_portal_id, p_member_data->>'name', p_member_data->>'role', p_member_data->>'email', p_member_data->>'phone');
        RETURN 'Membro adicionado com sucesso!';
    ELSIF p_action = 'update' THEN
        UPDATE public.team_members
        SET name = p_member_data->>'name',
            role = p_member_data->>'role',
            email = p_member_data->>'email',
            phone = p_member_data->>'phone'
        WHERE id = (p_member_data->>'id')::bigint AND portal_id = v_portal_id;
        RETURN 'Membro atualizado com sucesso!';
    ELSIF p_action = 'delete' THEN
        DELETE FROM public.team_members
        WHERE id = (p_member_data->>'id')::bigint AND portal_id = v_portal_id;
        RETURN 'Membro removido com sucesso!';
    ELSE
        RAISE EXCEPTION 'Ação inválida.';
    END IF;
END;
$$;

