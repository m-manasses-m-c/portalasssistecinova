-- 1.2. Formulários (Editais)
CREATE TABLE IF NOT EXISTS public.forms (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title text NOT NULL,
    description text,
    category text DEFAULT 'Edital',
    badge_text text DEFAULT 'Novo',
    documents jsonb DEFAULT '[]'::jsonb,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 1.3. Respostas
CREATE TABLE IF NOT EXISTS public.responses (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text,
    email text,
    ict text,
    campi jsonb,
    form_id bigint REFERENCES public.forms(id),
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Garantir colunas em tabelas existentes
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'responses' AND column_name = 'form_id') THEN
        ALTER TABLE public.responses ADD COLUMN form_id bigint REFERENCES public.forms(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'forms' AND column_name = 'badge_text') THEN
        ALTER TABLE public.forms ADD COLUMN badge_text text DEFAULT 'Novo';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'forms' AND column_name = 'category') THEN
        ALTER TABLE public.forms ADD COLUMN category text DEFAULT 'Edital';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'forms' AND column_name = 'documents') THEN
        ALTER TABLE public.forms ADD COLUMN documents jsonb DEFAULT '[]'::jsonb;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'forms' AND column_name = 'start_date') THEN
        ALTER TABLE public.forms ADD COLUMN start_date date;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'forms' AND column_name = 'end_date') THEN
        ALTER TABLE public.forms ADD COLUMN end_date date;
    END IF;
END $$;

-- 1.4. Eventos do Calendário
CREATE TABLE IF NOT EXISTS public.calendar_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title text NOT NULL,
    category text,
    start_date timestamp with time zone,
    end_date timestamp with time zone,
    scope text,
    target_ids jsonb,
    color text,
    form_id bigint REFERENCES public.forms(id),
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 1.5. Portais das ICTs
CREATE TABLE IF NOT EXISTS public.ict_portals (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ict_name text NOT NULL,
    access_key text NOT NULL,
    contact_name text,
    contact_email text,
    source_response_id bigint REFERENCES public.responses(id),
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL,
    UNIQUE(ict_name)
);

-- 1.6. Cronogramas dos Campi (Legado/Específico)
CREATE TABLE IF NOT EXISTS public.campus_schedules (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    response_id bigint REFERENCES public.responses(id),
    campus_id text,
    recess_start date,
    recess_end date,
    vac_start date,
    vac_end date,
    updated_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL,
    UNIQUE(response_id, campus_id)
);

-- 1.7. Membros da Equipe
CREATE TABLE IF NOT EXISTS public.team_members (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portal_id bigint REFERENCES public.ict_portals(id) ON DELETE CASCADE,
