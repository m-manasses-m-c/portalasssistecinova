-- 3.9. Portal: Obter Eventos
CREATE OR REPLACE FUNCTION public.get_events_for_portal(p_access_key text)
RETURNS json
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_portal public.ict_portals;
    v_response public.responses;
    v_form_id bigint;
BEGIN
    SELECT * INTO v_portal FROM public.ict_portals WHERE access_key = p_access_key;
    IF NOT FOUND THEN RAISE EXCEPTION 'Chave de acesso inválida'; END IF;

    SELECT * INTO v_response FROM public.responses WHERE id = v_portal.source_response_id;
    v_form_id := v_response.form_id;

    RETURN (
        SELECT COALESCE(json_agg(
            json_build_object(
                'title', e.title, 'category', e.category, 'start', e.start_date, 'end', e.end_date,
                'scope', e.scope, 'targetIds', e.target_ids, 'color', e.color
            )
        ), '[]'::json)
        FROM public.calendar_events e
        WHERE e.form_id = v_form_id
        AND (
            e.scope = 'global' 
            OR (e.scope = 'ict' AND e.target_ids @> to_jsonb(v_portal.ict_name))
        )
    );
END;
$$;

-- 3.10. Parceiro: Atualizar Eventos
CREATE OR REPLACE FUNCTION public.partner_update_events(p_access_key text, p_user_events jsonb)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_portal public.ict_portals;
    v_response public.responses;
    v_form_id bigint;
    evt jsonb;
    v_scope text;
    v_target_ids jsonb;
BEGIN
    -- 1. Validar Chave
    SELECT * INTO v_portal FROM public.ict_portals WHERE access_key = p_access_key;
    IF NOT FOUND THEN RAISE EXCEPTION 'Chave de acesso inválida'; END IF;

    SELECT * INTO v_response FROM public.responses WHERE id = v_portal.source_response_id;
    v_form_id := v_response.form_id;

    -- 2. Remover eventos existentes deste parceiro
    DELETE FROM public.calendar_events
    WHERE form_id = v_form_id
    AND scope = 'ict'
    AND target_ids = jsonb_build_array(v_portal.ict_name);

    DELETE FROM public.calendar_events
    WHERE form_id = v_form_id
    AND scope = 'campus'
    AND EXISTS (
        SELECT 1 
        FROM jsonb_array_elements_text(target_ids) tid
        WHERE tid IN (
            SELECT (c->>'id') 
            FROM jsonb_array_elements(v_response.campi) c
        )
    );

    -- 3. Inserir novos eventos
    IF jsonb_array_length(p_user_events) > 0 THEN
        FOR evt IN SELECT * FROM jsonb_array_elements(p_user_events)
        LOOP
            IF (evt->>'scope') = 'all' THEN
                v_scope := 'ict';
                v_target_ids := jsonb_build_array(v_portal.ict_name);
            ELSE
                v_scope := 'campus';
                v_target_ids := evt->'targetIds';
            END IF;

            INSERT INTO public.calendar_events (title, category, start_date, end_date, scope, target_ids, color, form_id) 
            VALUES (evt->>'title', evt->>'category', (evt->>'start')::timestamp, (evt->>'end')::timestamp, v_scope, v_target_ids, evt->>'color', v_form_id);
        END LOOP;
    END IF;

    RETURN 'Eventos salvos com sucesso!';
END;
$$;

