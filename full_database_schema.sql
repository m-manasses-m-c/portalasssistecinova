-- 3.3. Admin: Obter Dados do Dashboard
CREATE OR REPLACE FUNCTION public.get_admin_dashboard_data(admin_password text, p_form_id bigint)
RETURNS json
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    result json;
BEGIN
    IF admin_password <> 'admin123' THEN RAISE EXCEPTION 'Acesso Não Autorizado'; END IF;

    SELECT json_build_object(
        'responses', (
            SELECT COALESCE(json_agg(r), '[]'::json) 
            FROM public.responses r 
            WHERE (p_form_id IS NULL OR r.form_id = p_form_id)
        ),
        'portals', (
            SELECT COALESCE(json_agg(p), '[]'::json) FROM public.ict_portals p
            WHERE (p_form_id IS NULL OR EXISTS (SELECT 1 FROM public.responses r WHERE r.id = p.source_response_id AND r.form_id = p_form_id))
        ),
        'calendar', (
            SELECT json_build_object('events', COALESCE(json_agg(
                json_build_object(
                    'title', e.title, 'category', e.category, 'start', e.start_date, 'end', e.end_date,
                    'scope', e.scope, 'targetIds', e.target_ids, 'color', e.color
                )
            ), '[]'::json)) 
            FROM public.calendar_events e 
            WHERE (p_form_id IS NULL OR e.form_id = p_form_id)
        ),
        'schedules', (
            SELECT COALESCE(json_agg(s), '[]'::json)
            FROM public.campus_schedules s
            WHERE (p_form_id IS NULL OR EXISTS (SELECT 1 FROM public.responses r WHERE r.id = s.response_id AND r.form_id = p_form_id))
        ),
        'app_config', (SELECT row_to_json(c) FROM public.app_config c WHERE id = 1)
    ) INTO result;

    RETURN result;
END;
$$;

-- 3.4. Admin: Atualizar Eventos do Calendário
CREATE OR REPLACE FUNCTION public.admin_update_calendar_events(admin_password text, all_events jsonb, p_form_id bigint DEFAULT NULL)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    evt jsonb;
BEGIN
    IF admin_password <> 'admin123' THEN RAISE EXCEPTION 'Acesso Não Autorizado'; END IF;

    IF p_form_id IS NOT NULL THEN
        DELETE FROM public.calendar_events WHERE form_id = p_form_id;
    ELSE
        DELETE FROM public.calendar_events WHERE form_id IS NULL;
    END IF;

    IF jsonb_array_length(all_events) > 0 THEN
        FOR evt IN SELECT * FROM jsonb_array_elements(all_events)
        LOOP
            INSERT INTO public.calendar_events (title, category, start_date, end_date, scope, target_ids, color, form_id) 
            VALUES (evt->>'title', evt->>'category', (evt->>'start')::timestamp, (evt->>'end')::timestamp, evt->>'scope', evt->'targetIds', evt->>'color', p_form_id);
        END LOOP;
    END IF;
    RETURN 'Eventos atualizados com sucesso!';
END;
$$;

